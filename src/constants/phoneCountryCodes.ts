const toDigits = (value: string) => String(value || "").replace(/\D/g, "");

const normalizedDialCodes = [...PHONE_COUNTRY_CODES]
  .map((entry) => ({ ...entry, digitDial: toDigits(entry.dialCode) }))
  .sort((a, b) => b.digitDial.length - a.digitDial.length);

export const getDialCodeForCountry = (country: string): string | null => {
  const normalizedCountry = String(country || "").trim().toLowerCase();
  if (!normalizedCountry) return null;
  const match = PHONE_COUNTRY_CODES.find(
    (entry) => entry.country.toLowerCase() === normalizedCountry
  );
  return match?.dialCode || null;
};

export const splitPhoneNumber = (
  rawPhone: string | null | undefined,
  fallbackDialCode = "+1"
): { dialCode: string; localNumber: string } => {
  const value = String(rawPhone || "").trim();
  if (!value) {
    return { dialCode: fallbackDialCode, localNumber: "" };
  }

  const fullDigits = toDigits(value);
  if (!fullDigits) {
    return { dialCode: fallbackDialCode, localNumber: "" };
  }

  if (value.startsWith("+")) {
    const matched = normalizedDialCodes.find((entry) => fullDigits.startsWith(entry.digitDial));
    if (matched) {
      return {
        dialCode: matched.dialCode,
        localNumber: fullDigits.slice(matched.digitDial.length)
      };
    }
  }

  return { dialCode: fallbackDialCode, localNumber: fullDigits };
};

export const combinePhoneNumber = (dialCode: string, localNumber: string): string => {
  const normalizedDial = String(dialCode || "").trim().startsWith("+")
    ? String(dialCode || "").trim()
    : `+${toDigits(String(dialCode || ""))}`;
  const normalizedLocal = toDigits(localNumber);
  if (!normalizedLocal) return "";
  return `${normalizedDial}${normalizedLocal}`;
};

